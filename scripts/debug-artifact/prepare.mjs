import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { syncWorkspaceVersions } from '../sync-workspace-versions.mjs';
const root = process.cwd();
const require = createRequire(path.join(root, 'package.json'));
const { getConfig } = require('app-builder-lib/out/util/config/config.js');
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const base = pkg.version.replace(/-preview\.\d+$/, '');
const run = Number(process.env.GITHUB_RUN_NUMBER);
if (!Number.isSafeInteger(run) || run < 1 || run > 65535) throw new Error('Invalid Windows build number');
const version = `${base}-preview.${run}`;
pkg.version = version;
writeFileSync('package.json', `${JSON.stringify(pkg, null, 2)}\n`);
syncWorkspaceVersions(root);
const config = await getConfig(path.join(root, 'packages/desktop'), 'electron-builder.preview.yml', null);
delete config.extends;
config.appId = 'sh.paseo.plusplus.debug.desktop';
config.productName = 'Paseo++ Debug';
config.executableName = 'Paseo++ Debug';
config.extraMetadata = { ...config.extraMetadata, name: 'paseo-plus-plus-debug', productName: 'Paseo++ Debug', paseoPreview: true, paseoDebug: true };
config.protocols = [];
config.publish = null;
config.forceCodeSigning = false;
config.buildVersion = `${base}.${run}`;
config.win = { ...config.win, target: [{ target: 'zip', arch: ['x64'] }], artifactName: 'Paseo-Plus-Plus-Debug-${version}-windows-${arch}.${ext}', signAndEditExecutable: false };
delete config.win.azureSignOptions;
delete config.win.signtoolOptions;
const info = { kind: 'windows-debug-x64', commit: process.env.GITHUB_SHA, version, runId: process.env.GITHUB_RUN_ID, runUrl: `https://github.com/${process.env.GITHUB_REPOSITORY}/actions/runs/${process.env.GITHUB_RUN_ID}`, releasePublished: false, debugProfile: 'Paseo++ Debug', daemonHome: '.paseo-plus-plus-debug-desktop', daemonListen: '127.0.0.1:6791', selfUpdates: false };
writeFileSync('debug-build-info.json', `${JSON.stringify(info, null, 2)}\n`);
writeFileSync('Start-Paseo-Debug.cmd', '@echo off\r\nsetlocal\r\nset "PASEO_DEBUG=1"\r\n"%~dp0Paseo++ Debug.exe" --enable-logging %*\r\n');
writeFileSync('DEBUG-README.txt', 'Paseo++ Debug — Windows x64\r\n\r\nExtract the complete ZIP before launching. Run Start-Paseo-Debug.cmd for additional logs, or Paseo++ Debug.exe directly.\r\nThis build uses a separate Paseo++ Debug profile and .paseo-plus-plus-debug-desktop daemon home on port 6791. Automatic self-updates are disabled.\r\nConnect your host from the app. Build identity is in debug-build-info.json.\r\nThis is an unsigned test artifact, not a published release.\r\n');
config.extraFiles = [...(config.extraFiles ?? []), { from: path.join(root, 'Start-Paseo-Debug.cmd'), to: 'Start-Paseo-Debug.cmd' }, { from: path.join(root, 'DEBUG-README.txt'), to: 'DEBUG-README.txt' }, { from: path.join(root, 'debug-build-info.json'), to: 'debug-build-info.json' }];
writeFileSync('packages/desktop/electron-builder.debug.local.json', `${JSON.stringify(config, null, 2)}\n`);
